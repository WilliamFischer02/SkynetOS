export type IconName = keyof typeof ICONS;

interface Run { x: number; y: number; w: number }

function runsOf(rows: readonly string[]): Run[] {
  const out: Run[] = [];
  rows.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= row.length; x++) {
      const lit = row[x] === '#';
      if (lit && start < 0) start = x;
      if (!lit && start >= 0) { out.push({ x: start, y, w: x - start }); start = -1; }
    }
  });
  return out;
}

const RUNS = Object.fromEntries(Object.entries(ICONS).map(([name, rows]) => [name, runsOf(rows)])) as Record<IconName, Run[]>;

export const ICON_NAMES = Object.keys(ICONS) as IconName[];

/** The raw bitmap, for tests: every row nine characters of `#` and `.`. */
export function iconRows(name: IconName): readonly string[] {
  return ICONS[name];
}

export function Icon({ name, className, title }: { name: IconName; className?: string; title?: string }): React.JSX.Element {
  return (
    <svg
      className={className ? `ui-icon ${className}` : 'ui-icon'}
      viewBox="0 0 9 9"
      shapeRendering="crispEdges"
      fill="currentColor"
      {...(title ? { role: 'img', 'aria-label': title } : { 'aria-hidden': true })}
    >
      {RUNS[name].map((r) => <rect key={`${r.x},${r.y}`} x={r.x} y={r.y} width={r.w} height={1} />)}
    </svg>
  );
}
